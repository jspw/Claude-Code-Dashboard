/** Scope of a context-sharing export. */
export type ShareScope = 'project' | 'session';

/** A single file in a generated bundle, relative to the project root. */
export interface BundleFile {
  relativePath: string;
  content: string;
}

/** A session paired with the transcript filename assigned to it. */
export interface TranscriptEntry {
  sessionId: string;
  startTime: number;
  summary: string | null;
  files: string[];      // project-relative, deduped
  fileName: string;     // e.g. '2026-08-06-redesign-timeline.md'
}

